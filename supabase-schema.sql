create table if not exists public.gems (
    id bigint generated by default as identity primary key,
    name text not null,
    type text not null check (type in ('Sapphire', 'Emerald', 'Ruby', 'Other')),
    origin text not null,
    carat text not null,
    price text not null default 'POA',
    image text not null,
    description text not null,
    colour text not null,
    created_at timestamptz not null default now()
);

alter table public.gems enable row level security;

drop policy if exists "Anyone can read gems" on public.gems;
create policy "Anyone can read gems"
    on public.gems for select
    using (true);

